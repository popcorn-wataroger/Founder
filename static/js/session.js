// Founder - ログイン世代の管理（Issue #99）
//
// 何のためのファイルか:
//     アップロードやURL登録は fetch の応答が返るまでに時間がかかる。
//     その最中にログアウトして別の人がログインすると、応答が返った時点で
//     「前の人が選んだファイル名」が今ログインしている人の画面に表示される。
//     画面は #screen-chat などを作り直さず表示を切り替えているだけなので、
//     ステータス表示の要素は前の状態を保ったまま残るため。
//
//     サーバー側の権限判定は JWT で行われるため、資料の中身や他人の個別ソースが
//     漏れることはない。漏れるのはファイル名だけだが、Issue #74 の趣旨からすると
//     望ましくないため対処する。
//
// どう防ぐか:
//     ログインとログアウトのたびに数字（世代番号）を1つ進める。
//     通信を始める側は、始めた時点の世代番号を控えておき、応答が返ったあとに
//     「まだ同じ世代か」を確認してから画面を書き換える。
//     世代が変わっていれば、それは前の人の通信の結果なので画面には出さない。
//
//     admin.js の isStaffStillOpen() や source-manager.js の
//     commonSourceListRequestId と同じ「控えた値と現在値を突き合わせる」考え方を、
//     ログイン単位に広げたもの。
//
// なぜ AbortController ではないか:
//     対象の関数が3ファイル・4箇所に分かれており、進行中のリクエストを
//     ログアウト時にまとめて中止するには、リクエストを一元管理する仕組みを
//     別途持つ必要がある。世代番号なら、控えて突き合わせるだけで済む。

// 現在のログイン世代。ログイン・ログアウトのたびに1つ進む
let loginGeneration = 0;

/**
 * 世代番号を1つ進める。
 *
 * 入力: なし
 * 出力: なし（loginGeneration が変わる）
 *
 * ログイン成功時とログアウト時の両方から呼ぶ。
 * ログイン時だけでは足りない理由:
 *     ログアウトしてログイン画面にいる間に応答が返ると、その時点では
 *     世代が変わっていないため画面に書き込まれる。そのあとログインしても、
 *     ログイン時のクリア処理はすでに終わっているので消えない。
 */
function beginLoginGeneration() {
  loginGeneration++;
}

/**
 * 今の世代番号を返す。通信を始める前に控えるために使う。
 *
 * 入力: なし
 * 出力: 現在の世代番号（数値）
 */
function currentLoginGeneration() {
  return loginGeneration;
}

/**
 * 控えておいた世代番号が、今も有効かどうかを返す。
 *
 * 入力: generation … 通信を始めた時点で控えた世代番号
 * 出力: true なら同じログインが続いている / false なら別のログインに変わった
 */
function isSameLoginGeneration(generation) {
  return generation === loginGeneration;
}
