// Founder - APIを叩くときの共通のエラー処理（CodeRabbit の指摘対応）
//
// 何のためのファイルか:
//     fetch と res.json() が失敗したときのメッセージを日本語に揃える。
//     対処しないと、画面にブラウザ由来の英語がそのまま出る。
//         オフライン                    → "Failed to fetch"
//         プロキシがHTMLを返した場合    → "Unexpected token '<'..."
//     利用者はこれを読んでも何をすればいいか分からない。
//
// なぜ独立したファイルにするか:
//     使うのは account-admin.js（3箇所）と password-change.js（1箇所）の2ファイル。
//     どちらかに置くともう一方が依存することになり、
//     とくに password-change.js は4画面から使うため、
//     admin 専用画面のファイル（account-admin.js）に依存させたくない。
//     session.js に混ぜない理由は、あちらが「ログイン世代の管理」だけを
//     担当しているファイルで、役割が2つになるため。
//     このファイルは何にも依存せず、両方から一方向に参照される。
//
// 読み込む順番:
//     index.html で account-admin.js / password-change.js より前に置く。

/**
 * サーバーが返した、そのまま画面に出してよいメッセージを持つエラー。
 *
 * なぜ専用のクラスが要るか（重要）:
 *     catch には2種類の例外が来る。
 *       1. 自分が投げた「サーバーの detail」… そのまま表示したい（400 / 409 は日本語）
 *       2. fetch の通信失敗やコードのバグ  … 英語なので定型文に置き換えたい
 *     区別する目印が無いと、両方を定型文にして detail を捨てるか、
 *     両方そのまま出して英語を見せるかの二択になる。
 *     目印を1つ持てば、toDisplayMessage() が1行で振り分けられる。
 */
class ApiError extends Error {}

/**
 * 応答の本文をJSONとして読む。読めなければ null を返す。
 *
 * 入力: res … fetch が返した Response
 * 出力: 読み取れた場合はその値（オブジェクトや配列）。読めなければ null
 *
 * なぜ例外にせず null を返すのか:
 *     読めない理由（本文が空、HTMLが返ってきた、途中で切れた）を
 *     呼び出し元が区別しても、できることは変わらない。
 *     null を返して「本文は当てにできない」とだけ伝え、
 *     どう表示するかは呼び出し元が決める。
 *
 * どういうときに読めないか:
 *     プロキシやロードバランサがエラーページ（HTML）を返した場合や、
 *     204 のように本文が無い場合。
 */
async function parseJsonOrNull(res) {
  try {
    return await res.json();
  } catch (e) {
    return null;
  }
}

/**
 * catch で受け取った例外を、画面に出す日本語のメッセージにする。
 *
 * 入力: error … catch が受け取った値
 * 出力: 画面に表示する文字列
 *
 * 振り分け:
 *     ApiError            … サーバーが返した文言なので、そのまま返す
 *     それ以外（TypeError: Failed to fetch、コードのバグなど）
 *                         … 定型文に置き換える
 *
 * 想定外の例外も定型文にする理由:
 *     コードのバグで出た英語のメッセージを画面に出しても、
 *     利用者にできることは無い。「通信に失敗した」とだけ伝えて、
 *     やり直せることを示す方が役に立つ。
 */
function toDisplayMessage(error) {
  if (error instanceof ApiError) return error.message;
  return "通信に失敗しました。ネットワークの状態を確認してください。";
}
